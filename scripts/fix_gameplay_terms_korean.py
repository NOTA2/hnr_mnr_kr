def main() -> None:
    arr = json.loads(WORKSET.read_text())
    changed = 0
    for record in arr:
        src = record["text"]
        if src in OVERRIDES:
            new_value = OVERRIDES[src]
            if record.get("translation") != new_value:
                record["translation"] = new_value
                changed += 1
    WORKSET.write_text(json.dumps(arr, ensure_ascii=False, indent=2) + "\n")
    print(f"updated={changed}")


if __name__ == "__main__":
    main()
